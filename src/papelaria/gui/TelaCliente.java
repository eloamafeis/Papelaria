    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        if (txtNome.getText().trim().isEmpty() || txtCpf.getText().trim().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Nome e CPF são obrigatórios!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    papelaria.estoque.Cliente c = new papelaria.estoque.Cliente();
    c.setNome(txtNome.getText().trim());
    c.setCpf(txtCpf.getText().trim());
    c.setTelefone(txtTelefone.getText().trim());
    c.setEmail(txtEmail.getText().trim());

    if (clienteDAO.cadastrar(c)) {
        javax.swing.JOptionPane.showMessageDialog(this, "Cliente cadastrado no banco com sucesso!");
        limparCampos();
        preencherTabela();
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Erro ao cadastrar cliente no banco de dados.", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int linhaView = tblClientes.getSelectedRow();
    if (linhaView < 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Selecione um cliente na tabela para editar!");
        return;
    }

    int linha = tblClientes.convertRowIndexToModel(linhaView);
    papelaria.estoque.Cliente c = listaAtual.get(linha);
    c.setNome(txtNome.getText().trim());
    c.setCpf(txtCpf.getText().trim());
    c.setTelefone(txtTelefone.getText().trim());
    c.setEmail(txtEmail.getText().trim());

    if (clienteDAO.editar(c)) {
        javax.swing.JOptionPane.showMessageDialog(this, "Cliente atualizado com sucesso!");
        limparCampos();
        preencherTabela();
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Erro ao atualizar cliente.", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int linhaView = tblClientes.getSelectedRow();
    if (linhaView < 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Selecione um cliente na tabela para excluir!");
        return;
    }

    int confirmacao = javax.swing.JOptionPane.showConfirmDialog(this, "Tem certeza que deseja excluir este cliente?", "Confirmar Exclusão", javax.swing.JOptionPane.YES_NO_OPTION);
    if (confirmacao == javax.swing.JOptionPane.YES_OPTION) {
        int linha = tblClientes.convertRowIndexToModel(linhaView);
        papelaria.estoque.Cliente c = listaAtual.get(linha);

        if (clienteDAO.excluir(c.getId())) {
            javax.swing.JOptionPane.showMessageDialog(this, "Cliente excluído com sucesso!");
            limparCampos();
            preencherTabela();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao excluir cliente do banco de dados.", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }
    }//GEN-LAST:event_btnExcluirActionPerformed

