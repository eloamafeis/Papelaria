private void preencherTabela() {
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblClientes.getModel();
        model.setRowCount(0);
        listaAtual = clienteDAO.listarTodos();
        for (papelaria.estoque.Cliente c : listaAtual) {
            model.addRow(new Object[]{
                c.getId(),
                c.getNome(),
                c.getCpf(),
                c.getTelefone(),
                c.getEmail()
            });
        }
    }

    private void mostrarClienteSelecionado() {
        int linhaView = tblClientes.getSelectedRow();
        if (linhaView < 0) return;

        int linha = tblClientes.convertRowIndexToModel(linhaView);
        if (linha >= listaAtual.size()) return;

        papelaria.estoque.Cliente c = listaAtual.get(linha);
        txtNome.setText(c.getNome());
        txtCpf.setText(c.getCpf());
        txtTelefone.setText(c.getTelefone());
        txtEmail.setText(c.getEmail());
    }

    private void limparCampos() {
        txtNome.setText("");
        txtCpf.setValue(null);
        txtTelefone.setValue(null);
        txtEmail.setText("");
        tblClientes.clearSelection();
    }
    private void aplicarMascaras() {
    try {
        // Máscara de CPF: 000.000.000-00
        javax.swing.text.MaskFormatter mascaraCpf = new javax.swing.text.MaskFormatter("###.###.###-##");
        mascaraCpf.setPlaceholderCharacter('_');
        mascaraCpf.install(txtCpf);

        // Máscara de Telefone: (00) 00000-0000
        javax.swing.text.MaskFormatter mascaraTel = new javax.swing.text.MaskFormatter("(##) #####-####");
        mascaraTel.setPlaceholderCharacter('_');
        mascaraTel.install(txtTelefone);
    } catch (java.text.ParseException e) {
        System.err.println("Erro ao aplicar máscara: " + e.getMessage());
    }
}
    
