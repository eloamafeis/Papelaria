    private void btnFinalizarVendaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFinalizarVendaActionPerformed
     try {
        // Validação inicial
        if (cmbCliente.getSelectedItem() == null || listaItens.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione um cliente e adicione pelo menos um item!");
            return;
        }

   
        papelaria.estoque.Cliente clienteEstoque = (papelaria.estoque.Cliente) cmbCliente.getSelectedItem();

     
        papelaria.pessoa.Cliente clientePessoa = new papelaria.pessoa.Cliente();
        clientePessoa.setId(clienteEstoque.getId());

  
        papelaria.operacao.Venda venda = new papelaria.operacao.Venda();
        venda.setCliente(clientePessoa);
       

        venda.setValorTotal(valorTotal);
        venda.setItens(listaItens);

       
        if (vendaDAO.salvarVenda(venda)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Venda realizada com sucesso!");
            listaItens.clear();
            atualizarTabela();
            carregarProdutos(); 
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao salvar a venda no banco de dados.");
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Erro no formulário: " + e.getMessage());
        e.printStackTrace();
    }
    }//GEN-LAST:event_btnFinalizarVendaActionPerformed
    
    private void btnAddItemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddItemActionPerformed
       papelaria.estoque.Produto produtoSelecionado = (papelaria.estoque.Produto) cmbProduto.getSelectedItem();
        
        if (produtoSelecionado == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione um produto!");
            return;
        }

        // Lê o valor diretamente do JSpinner (spnQuantidade)
        int qtd = (Integer) spnQuantidade.getValue();

        if (qtd <= 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "A quantidade deve ser maior que zero!");
            return;
        }

        if (qtd > produtoSelecionado.getEstoque()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Estoque insuficiente! Disponível: " + produtoSelecionado.getEstoque());
            return;
        }

        papelaria.operacao.ItemVenda item = new papelaria.operacao.ItemVenda(produtoSelecionado, qtd, produtoSelecionado.getPreco());
        listaItens.add(item);
        atualizarTabela();
        
        // Reseta o Spinner para 1 após adicionar
        spnQuantidade.setValue(1);
    }//GEN-LAST:event_btnAddItemActionPerformed
        private void carregarClientes() {
        cmbCliente.removeAllItems();
         java.util.List<papelaria.estoque.Cliente> clientes = clienteDAO.listarTodos();
        for (papelaria.estoque.Cliente c : clientes) {
        ((javax.swing.DefaultComboBoxModel) cmbCliente.getModel()).addElement(c);
        }
    }

    private void carregarProdutos() {
        cmbProduto.removeAllItems();
        java.util.List<papelaria.estoque.Produto> produtos = produtoDAO.listarTodos();
        for (papelaria.estoque.Produto p : produtos) {
            ((javax.swing.DefaultComboBoxModel) cmbProduto.getModel()).addElement(p);
        }
    }

    private void aplicarFormatacaoTotal() {
        try {
            java.text.DecimalFormat df = new java.text.DecimalFormat("R$ #,##0.00");
            javax.swing.text.NumberFormatter formatter = new javax.swing.text.NumberFormatter(df);
            formatter.setValueClass(Double.class);

            txtTotal.setFormatterFactory(new javax.swing.text.DefaultFormatterFactory(formatter));
            txtTotal.setValue(0.00);
            txtTotal.setEditable(false); // Impede que o usuário digite o total manualmente
        } catch (Exception e) {
            logger.log(java.util.logging.Level.SEVERE, "Erro ao formatar total", e);
        }
    }
    
    private void atualizarTabela() {
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblItens.getModel();
        model.setRowCount(0);
        valorTotal = 0.0;

        for (papelaria.operacao.ItemVenda item : listaItens) {
            model.addRow(new Object[]{
                item.getProduto().getNome(),
                item.getQuantidade(),
                item.getValorUnitario(),
                item.getSubtotal()
            });
            valorTotal += item.getSubtotal();
        }
        
        // Atualiza a variável txtTotal usando setValue
        txtTotal.setValue(valorTotal);
    }

    
