private void aplicarFormatacaoPreco() {
    try {
        // Configura o formatador de números decimais
        java.text.DecimalFormat df = new java.text.DecimalFormat("#,##0.00");
        javax.swing.text.NumberFormatter formatter = new javax.swing.text.NumberFormatter(df);
        formatter.setValueClass(Double.class);
        formatter.setAllowsInvalid(false); // Não permite digitar letras
        formatter.setMinimum(0.00);        // Não permite valores negativos

        txtPreco.setFormatterFactory(new javax.swing.text.DefaultFormatterFactory(formatter));
        txtPreco.setValue(0.00);           // Valor inicial
    } catch (Exception e) {
        System.err.println("Erro ao formatar campo de preço: " + e.getMessage());
    }
}
private void preencherTabela() {
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tblProdutos.getModel();
        model.setRowCount(0);
        listaAtual = produtoDAO.listarTodos();
        for (papelaria.estoque.Produto p : listaAtual) {
            model.addRow(new Object[]{p.getId(), p.getNome(), p.getPreco(), p.getEstoque()});
        }
    }

    private void mostrarProdutoSelecionado() {
        int linhaView = tblProdutos.getSelectedRow();
        if (linhaView < 0) return;

        int linha = tblProdutos.convertRowIndexToModel(linhaView);
        if (linha >= listaAtual.size()) return;

        papelaria.estoque.Produto p = listaAtual.get(linha);
        txtNome.setText(p.getNome());
        txtPreco.setValue(p.getPreco());
        spnEstoque.setValue(p.getEstoque());

        caminhoImagemSelecionada = (p.getImagem() != null) ? p.getImagem() : "";
        exibirImagem(caminhoImagemSelecionada);
    }

    private void limparCampos() {
        txtNome.setText("");
        txtPreco.setValue(0.00);
        spnEstoque.setValue(0);
        caminhoImagemSelecionada = "";
        lblFoto.setIcon(null);
        tblProdutos.clearSelection();
    }

    private void exibirImagem(String caminho) {
        if (caminho != null && !caminho.trim().isEmpty() && new java.io.File(caminho).exists()) {
            javax.swing.ImageIcon icon = new javax.swing.ImageIcon(caminho);
            java.awt.Image img = icon.getImage().getScaledInstance(
                lblFoto.getWidth() > 0 ? lblFoto.getWidth() : 114,
                lblFoto.getHeight() > 0 ? lblFoto.getHeight() : 169,
                java.awt.Image.SCALE_SMOOTH
            );
            lblFoto.setIcon(new javax.swing.ImageIcon(img));
        } else {
            lblFoto.setIcon(null);
        }
    }
