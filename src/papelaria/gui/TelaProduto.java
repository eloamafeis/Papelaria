    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        if (txtNome.getText().trim().isEmpty() || txtPreco.getValue() == null) {
        javax.swing.JOptionPane.showMessageDialog(this, "Preencha o nome e o preço do produto!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    double preco;
    int estoque;

    try {
        // Pega o valor numérico do JFormattedTextField de Preço
        preco = ((Number) txtPreco.getValue()).doubleValue();
        
        // Pega o valor numérico do JSpinner de Estoque
        estoque = (Integer) spnEstoque.getValue();
    } catch (Exception ex) {
        javax.swing.JOptionPane.showMessageDialog(this, "Preço e estoque devem ser valores válidos!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    papelaria.estoque.Produto p = new papelaria.estoque.Produto();
    p.setNome(txtNome.getText().trim());
    p.setPreco(preco);
    p.setEstoque(estoque);
    p.setImagem(caminhoImagemSelecionada);

    if (produtoDAO.cadastrar(p)) {
        javax.swing.JOptionPane.showMessageDialog(this, "Produto cadastrado com sucesso!");
        limparCampos();
        preencherTabela();
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Erro ao cadastrar o produto.", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
      int linhaView = tblProdutos.getSelectedRow();
    if (linhaView < 0) {
        javax.swing.JOptionPane.showMessageDialog(this, "Selecione um produto na tabela para excluir.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    int linha = tblProdutos.convertRowIndexToModel(linhaView);
    papelaria.estoque.Produto p = listaAtual.get(linha);

    int opcao = javax.swing.JOptionPane.showConfirmDialog(this,
            "Deseja excluir o produto \"" + p.getNome() + "\"?",
            "Confirmar exclusão",
            javax.swing.JOptionPane.YES_NO_OPTION);
    if (opcao != javax.swing.JOptionPane.YES_OPTION) {
        return;
    }

    if (produtoDAO.excluir(p.getId())) {
        javax.swing.JOptionPane.showMessageDialog(this, "Produto excluído com sucesso!");
        limparCampos();
        preencherTabela();
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Não foi possível excluir o produto.", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnSelecionarImagemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSelecionarImagemActionPerformed
      javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();
    fileChooser.setDialogTitle("Selecionar Foto do Produto");
    fileChooser.setFileFilter(new javax.swing.filechooser.FileNameExtensionFilter("Imagens (JPG, PNG)", "jpg", "jpeg", "png"));

    int resultado = fileChooser.showOpenDialog(this);
    if (resultado == javax.swing.JFileChooser.APPROVE_OPTION) {
        java.io.File origem = fileChooser.getSelectedFile();
        try {
            java.io.File pasta = new java.io.File("imagens");
            if (!pasta.exists()) {
                pasta.mkdirs();
            }

            java.io.File destino = new java.io.File(pasta, System.currentTimeMillis() + "_" + origem.getName());
            java.nio.file.Files.copy(origem.toPath(), destino.toPath(),
                    java.nio.file.StandardCopyOption.REPLACE_EXISTING);

            caminhoImagemSelecionada = destino.getPath();
            exibirImagem(caminhoImagemSelecionada);
        } catch (java.io.IOException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao copiar a imagem: " + ex.getMessage());
        }
    }
    }//GEN-LAST:event_btnSelecionarImagemActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        int linhaView = tblProdutos.getSelectedRow();
        if (linhaView < 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Selecione um produto para editar.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (txtNome.getText().trim().isEmpty() || txtPreco.getValue() == null) {
            javax.swing.JOptionPane.showMessageDialog(this, "Preencha o nome e o preço do produto!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        double preco;
        int estoque;
        try {
            preco = ((Number) txtPreco.getValue()).doubleValue();
            estoque = (Integer) spnEstoque.getValue();
        } catch (Exception ex) {
            javax.swing.JOptionPane.showMessageDialog(this, "Preço e estoque devem ser números válidos!", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        int linha = tblProdutos.convertRowIndexToModel(linhaView);
        papelaria.estoque.Produto p = listaAtual.get(linha);
        p.setNome(txtNome.getText().trim());
        p.setPreco(preco);
        p.setEstoque(estoque);
        p.setImagem(caminhoImagemSelecionada); // Mantido o padrão setImagem como no btnSalvar

        if (produtoDAO.editar(p)) { // Se o seu DAO usar atualizar(p), mude aqui para produtoDAO.atualizar(p)
            javax.swing.JOptionPane.showMessageDialog(this, "Produto atualizado com sucesso!");
            limparCampos();
            preencherTabela();
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Erro ao atualizar produto.", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnEditarActionPerformed

