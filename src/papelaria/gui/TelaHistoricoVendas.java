 private void carregarHistorico() {
       DefaultTableModel model = (DefaultTableModel) tblHistorico.getModel();
        model.setRowCount(0); 

        java.util.List<Object[]> historico = vendaDAO.listarHistoricoVendas();
        for (Object[] linha : historico) {
            linha[4] = String.format("R$ %.2f", (Double) linha[4]);
            linha[5] = String.format("R$ %.2f", (Double) linha[5]);
            model.addRow(linha);
        }
    }
   
